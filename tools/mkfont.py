#!/usr/bin/env python3
"""Generate common/src/font_data.c from the public-domain X11 misc-fixed
bitmap fonts (Debian package xfonts-base): 6x10 (text) and 10x20 (big digits).

usage: python3 tools/mkfont.py > common/src/font_data.c
"""
import gzip
import io
import os
import tempfile

from PIL import Image, ImageDraw, ImageFont, PcfFontFile

FONTS = [("6x10", 6, 10, "uint8_t"), ("10x20", 10, 20, "uint16_t")]
FIRST, LAST = 32, 126


def load(name, tmp):
    data = gzip.open(f"/usr/share/fonts/X11/misc/{name}.pcf.gz").read()
    pcf = PcfFontFile.PcfFontFile(io.BytesIO(data))
    base = os.path.join(tmp, name)
    pcf.save(base)
    return ImageFont.load(base + ".pil")


def main():
    print("/* Generated by tools/mkfont.py from X11 misc-fixed fonts (public domain). */")
    print('#include "aqm/font.h"\n')
    with tempfile.TemporaryDirectory() as tmp:
        for name, w, h, ctype in FONTS:
            font = load(name, tmp)
            cname = "f" + name.replace("x", "_")
            print(f"static const {ctype} {cname}_bits[{LAST - FIRST + 1}][{h}] = {{")
            for c in range(FIRST, LAST + 1):
                im = Image.new("1", (w, h), 0)
                ImageDraw.Draw(im).text((0, 0), chr(c), font=font, fill=1)
                px = im.load()
                rows = []
                for y in range(h):
                    v = 0
                    for x in range(w):
                        if px[x, y]:
                            v |= 1 << (w - 1 - x)       # MSB = leftmost pixel
                    rows.append(f"0x{v:0{(w + 3) // 4}x}")
                ch = chr(c).replace("\\", "backslash")
                print(f"    {{{', '.join(rows)}}}, /* '{ch}' */")
            print("};\n")
            print(f"const aqm_font_t font_{name.replace('x', '_')} = "
                  f"{{ {w}, {h}, {FIRST}, {LAST}, sizeof({ctype}), {cname}_bits }};\n")


if __name__ == "__main__":
    main()
